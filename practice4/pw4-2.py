
import math # подключаем модуль math

x1 = float(input('x1 = ')) # запрос данных у пользователя
y1 = float(input('y1 = ')) # запрос данных у пользователя
x2 = float(input('x2 = ')) # запрос данных у пользователя
y2 = float(input('y2 = ')) # запрос данных у пользователя

p = math.sqrt((x1 - x2) ** 2 + (y1 - y2) ** 2) # подсчёт расстояния
print('Расстояние между точками =', p) # вывод результата
