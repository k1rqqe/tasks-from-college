
place = int(input('Введите место в вагоне: ')) # запрос данных у пользователя

if 1 <= place <= 36: # проверка на диапазон мест
    coupe = (place // 4) + 1 # подсчёт номера купе
    print("Ваше место в купе №", coupe) # вывод результата
else: # если места нет в диапозоне
    print('Такого места в вагоне нет') # вывод результата 
